#!/usr/bin/env node
/**
 * Emit a `.d.ts` beside every `*.module.css` naming its exact class names.
 *
 * Why this exists instead of the usual generic declaration:
 *
 * The project runs with `noPropertyAccessFromIndexSignature`, which is valuable — it forces
 * bracket access on genuinely dynamic lookups (see `src/services/import/legacy.ts`, where every
 * read of an untrusted legacy field is `source['field']` and reads as the untrusted access it is).
 * The conventional CSS-module declaration is `Record<string, string>`, an index signature, so it
 * would make `styles.card` an error and push us to disable the flag project-wide.
 *
 * Generating the real class list keeps the flag on *and* buys a check the generic declaration
 * cannot give: a typo'd class name is a compile error rather than a silently `undefined` value
 * that drops the element's styling without failing a test.
 *
 * The output is deterministic and committed. If a stylesheet changes without regenerating, the
 * typecheck fails loudly, which is the intended behaviour. `npm run typecheck` and `npm run build`
 * both run this first.
 *
 * Run: node scripts/generate-css-module-types.mjs [--check]
 */

import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SRC = join(ROOT, 'src');

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (entry.endsWith('.module.css')) out.push(full);
  }
  return out;
}

/**
 * Collect class selectors.
 *
 * Comments are stripped first so a commented-out rule cannot contribute a name, and `@media`
 * blocks need no special handling because the regex matches selectors wherever they appear.
 * Pseudo-classes and combinators are excluded by requiring the match to start at a `.`.
 */
function extractClassNames(css) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const names = new Set();
  const pattern = /\.(-?[_a-zA-Z][\w-]*)/g;
  let match;
  while ((match = pattern.exec(withoutComments)) !== null) {
    const name = match[1];
    if (name) names.add(name);
  }
  return [...names].sort();
}

function render(names, sourceName) {
  const body =
    names.length === 0
      ? '  // no class selectors in this stylesheet\n  readonly __empty?: never;'
      : names.map((name) => `  readonly ${JSON.stringify(name)}: string;`).join('\n');
  return `// Generated by scripts/generate-css-module-types.mjs from ${sourceName}. Do not edit.
declare const classes: {
${body}
};
export default classes;
`;
}

function main() {
  const check = process.argv.includes('--check');
  const files = existsSync(SRC) ? walk(SRC) : [];
  let changed = 0;

  for (const file of files) {
    const css = readFileSync(file, 'utf8');
    const names = extractClassNames(css);
    const target = `${file}.d.ts`;
    const next = render(names, relative(ROOT, file).replaceAll('\\', '/'));
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== next) {
      changed += 1;
      if (check) {
        console.error(`stale or missing: ${relative(ROOT, target).replaceAll('\\', '/')}`);
      } else {
        writeFileSync(target, next, 'utf8');
      }
    }
  }

  if (check && changed > 0) {
    console.error(
      `\n${changed} CSS module type file(s) are out of date. Run: node scripts/generate-css-module-types.mjs`,
    );
    process.exit(1);
  }
  console.log(
    check
      ? `checked ${files.length} stylesheet(s): all type declarations current`
      : `generated ${files.length} declaration(s), ${changed} updated`,
  );
}

main();
